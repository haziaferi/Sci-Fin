/*
 * §2.5 -- the token system: eleven tokens per mode, twenty-two per theme, eighty-eight across
 * the app, transcribed from the spec's tables (post-remedy values). No valence colour anywhere
 * (§2.1): each theme carries exactly one accent.
 */

data class Palette(
    val bg: Color, val surf: Color, val surf2: Color,
    val bord: Color, val bordStrong: Color,
    val txt: Color, val txt2: Color, val txt3: Color,
    val acc: Color, val accH: Color, val onAcc: Color,
)

