/**
 * §2.5's type: one size per job. Body IS the device's text
 * size; the other three are fixed ratios of it on a perfect fourth, so they move with it. Two
 * weights only, Regular and Bold. See [typeRamp].
 */
data class TypeRamp(
    /** Captions, chart labels, sources, section labels (bold, uppercase), the navigation labels. */
    val caption: TextUnit,
    /** Everything read as text: paragraphs, rows, fields, buttons; bold where a row names something. */
    val body: TextUnit,
    /** A screen's, page's or sheet's title, and a result that heads a card. */
    val title: TextUnit,
    /** The one headline amount or count a view is about. */
    val figure: TextUnit,
)

/** §2.5's spacing: `u` from density, `pad` = 1.75u, `gap` = 1u; targets never shrink with density. */
data class Spacing(val u: Dp, val pad: Dp, val gap: Dp, val target: Dp)

/**
 * §2.1/§5: the bar, the sparkline and the month columns keep their 360dp-phone aspect ratio
 * (308 × 5, 306 × 64, 332 × 150dp) at every width; heights are bounded by §4.8's measure. The
 * hatch stroke and the tick stay on `radii.micro` and `strokes`, off this axis.
 */
object ChartShapes {
    const val BAR = 308f / 5f
    const val SPARKLINE = 306f / 64f
    const val MONTH_COLUMNS = 332f / 150f
}

/** §2.5's geometry: seven radii and four strokes (the sparkline's `line` among them) on `ru` = 8dp, fixed dp on every axis. */
data class Radii(val micro: Dp, val tiny: Dp, val sm: Dp, val md: Dp, val lg: Dp, val xl: Dp, val sheet: Dp)
data class Strokes(val hair: Dp, val ctl: Dp, val emph: Dp, val line: Dp)

val RADII = Radii(micro = 3.dp, tiny = 6.dp, sm = 8.dp, md = 12.dp, lg = 14.dp, xl = 16.dp, sheet = 22.dp)
val STROKES = Strokes(hair = 0.5.dp, ctl = 1.5.dp, emph = 2.dp, line = 2.5.dp)

/** The dimming behind a sheet (0.42) and around the tour's spotlight (0.5): one ink, every theme. */
val SCRIM = Color(0xFF0A0A0E)

data class SciFinTokens(
    val palette: Palette, val type: TypeRamp, val spacing: Spacing, val dark: Boolean, val reduceMotion: Boolean, val lowDistraction: Boolean,
    /** Fixed dp on every axis: a corner and a stroke are properties of the shape (§2.5). */
    val radii: Radii = RADII, val strokes: Strokes = STROKES,
    val icons: IconSizes = iconSizes(),
    /** What the screen factor resolved to, kept so a screen can reason about it without re-measuring. */
    val screenScale: Float = 1f,
    /** §4.8's measure: the widest a column or a paragraph may run. See [measureFor]. */
    val measure: Dp = measureFor(1f),
)

/**
 * §2.5's four sizes on a perfect fourth (1.333) from a 16px body: caption 0.75, body 1, title
 * 1.333, figure 1.777 -- 12 / 16 / 21.3 / 28.4px at the device's default text size. In `sp`, so
 * the device's text size multiplies all four together and the ratios hold.
 */
fun typeRamp(): TypeRamp {
    val body = 16f
    return TypeRamp(caption = (body * 0.75f).sp, body = body.sp, title = (body * 1.3333f).sp, figure = (body * 1.7777f).sp)
}

fun spacing(density: Density, targetDp: Int, screenScale: Float = 1f): Spacing {
    // §2.5: density × screen factor, `u` floored at 6dp.
    val u = (density.unitPx * screenScale).coerceAtLeast(6f).dp
    return Spacing(u = u, pad = u * 1.75f, gap = u, target = targetDp.dp)
}

/**
 * §2.5's screen factor, for the phone.
 *
 * Below 600dp there is no navigation rail and no second pane, so the window and the column a
 * person reads are the same number: width ÷ 360dp, floored at 0.85, no ceiling -- the phone
 * range is 0.89 at 320dp to about 1.33 at 480dp, too narrow for a ceiling to buy anything.
 *
 * At 600dp and above it is 1 until §4.8 settles the desktop's reference: the window is one
 * number, its rail, list column and detail column are three others.
 */
fun screenScale(widthDp: Float): Float =
    if (widthDp >= 600f) 1f else (widthDp / 360f).coerceAtLeast(0.85f)

/** §2.5: icon and glyph sizes, on the screen axis with spacing. */
data class IconSizes(val xs: Dp, val sm: Dp, val md: Dp, val lg: Dp)

fun iconSizes(screenScale: Float = 1f) = IconSizes(
    xs = (12 * screenScale).dp, sm = (14 * screenScale).dp, md = (16 * screenScale).dp, lg = (20 * screenScale).dp,
)

/**
 * §4.8's measure: 52 characters of body text (`16 × 0.55 × 52` = 458dp) × [fontScale], since
 * body is the device's text size; a window too narrow for two such columns reflows to one
 * (WCAG 1.4.10).
 */
fun measureFor(fontScale: Float): Dp = (16f * 0.55f * 52 * fontScale).dp

/** Resolves §2.5's settings, the platform's dark preference and the screen factor into one token set. */

fun tokensFor(settings: Settings, systemDark: Boolean, targetDp: Int, screenScale: Float = 1f, fontScale: Float = 1f): SciFinTokens {
    val dark = when (settings.mode) { ThemeMode.SYSTEM -> systemDark; ThemeMode.DARK -> true; ThemeMode.LIGHT -> false }
    return SciFinTokens(
        palette = Palettes.of(settings.theme, dark),
        type = typeRamp(),
        spacing = spacing(settings.density, targetDp, screenScale),
        icons = iconSizes(screenScale),
        screenScale = screenScale,
        measure = measureFor(fontScale),
        dark = dark, reduceMotion = settings.reduceMotion, lowDistraction = settings.lowDistraction,
    )
}

val LocalTokens = staticCompositionLocalOf<SciFinTokens> { error("SciFinTheme not applied") }

/**
 * The tokens are the theme; Material's colour scheme is derived from them so the few Material
 * components the app uses (the date picker) take the palette rather than Material's own.
 */
@Composable
fun SciFinTheme(tokens: SciFinTokens, content: @Composable () -> Unit) {
    val p = tokens.palette
    val scheme = (if (tokens.dark) darkColorScheme() else lightColorScheme()).copy(
        primary = p.acc, onPrimary = p.onAcc, secondary = p.acc, onSecondary = p.onAcc, tertiary = p.acc,
        background = p.bg, onBackground = p.txt, surface = p.surf, onSurface = p.txt,
        surfaceVariant = p.surf2, onSurfaceVariant = p.txt2, surfaceContainerHigh = p.surf, surfaceContainer = p.surf,
        outline = p.bordStrong, outlineVariant = p.bord, primaryContainer = p.surf2, onPrimaryContainer = p.txt,
    )
    MaterialTheme(colorScheme = scheme) {
        CompositionLocalProvider(LocalTokens provides tokens, content = content)
    }
}
